"""Render benchmarks/apple/mlx/README.md tables from bench-*.json and parity.json (numbers are copied, never re-measured)."""
import json
from common import ROOT

D = ROOT / "benchmarks/apple/mlx"
L = ["# MLX TingMix-Large: measured results", "", "Generated by `experiments/macos/mlx/report.py` from the raw JSON next to this file. Commands are in each JSON (`cmd`).", ""]
for name, title in (("fp32", "fp32 (GPU)"), ("fp16", "fp16 (GPU)"), ("bf16", "bf16 (GPU)"), ("fp32-cpu", "fp32 (MLX CPU stream, GPU-use control)")):
    j = json.loads((D / f"bench-{name}.json").read_text())
    L += [f"## Latency: {title}", "", f"{j['device']['model']}, {j['device']['os']}, mlx {j['versions']['mlx']}, peak RSS {j['peak_rss_final_mib']:.0f} MiB (after load {j['peak_rss_after_load_mib']:.0f}), load {j['load_s']:.2f} s, loadavg at end {j['loadavg_end'][0]:.1f}", "",
          "| audio s | enc frames | P50 ms | P95 ms | P99 ms | RTF P50 | mel / tower / reader+greedy ms | MLX peak MiB | CPU cores busy | runs |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in j["rows"]:
        t, p = r["total_ms"], r["phase_ms_mean"]
        L.append(f"| {r['audio_s']} | {r['frames']} | {t['p50']:.0f} | {t['p95']:.0f} | {t['p99']:.0f} | {r['rtf_p50']:.4f} | {p['mel']:.0f} / {p['tower']:.0f} / {p['reader_greedy']:.0f} | {r['mlx_peak_mem_mib']:.0f} | {r['cpu_cores_busy']:.2f} | {r['runs']} |")
    L.append("")
p = json.loads((D / "parity.json").read_text())["rows"]
L += ["## Parity summary vs PyTorch CPU fp32 (worst case over 8 fixtures)", "", "| dtype | feat max-abs | cos min | logit max-abs | argmax agree min | greedy exact | beam+LM exact |", "|---|---|---|---|---|---|---|"]
for d in ("fp32", "fp16", "bf16"):
    r = [x for x in p if x["dtype"] == d]
    L.append(f"| {d} | {max(x['feat_max_abs'] for x in r):.2e} | {min(x['cos_min'] for x in r):.6f} | {max(x['logit_max_abs'] for x in r):.2e} | {min(x['argmax_agree'] for x in r):.4f} | {sum(x['greedy_match'] for x in r)}/{len(r)} | {sum(x['beam_match'] for x in r)}/{len(r)} |")
(D / "README.md").write_text("\n".join(L) + "\n")
